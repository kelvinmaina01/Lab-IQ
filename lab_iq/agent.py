# --- Internal Thought Process ---
class PlanStep(BaseModel):
    step_number: int
    activity: str
    rationale: str

class AnalystPlan(BaseModel):
    """The 'Architect's Blueprint' generated by Gemini"""
    objective_understanding: str
    steps: List[PlanStep]
    data_requirements: List[str]
    potential_challenges: List[str]

class CodingTask(BaseModel):
    """The 'Engineering Task' generated by Groq"""
    python_code: str = Field(description="Executable pandas code. MUST define 'metrics' dict and use plt.show() or plt.savefig().")
    explanation: str

class InsightContent(BaseModel):
    summary: str
    key_evidence: List[str]
    notable_examples: List[str]
    implications: List[str]
    confidence: Literal["high", "medium", "low"]

class PinMetadata(BaseModel):
    pin_eligible: bool
    suggested_title: str
    suggested_description: str
    pin_tags: List[str] = Field(default_factory=list)
    source_cells: List[str] = Field(default_factory=list)
    drilldown_path: Dict[str, Any] = Field(default_factory=dict) # e.g. {"type": "notebook", "target_cell_ids": []}

# --- Final Notebook Schema (Per XML) ---
class NotebookCell(BaseModel):
    cell_id: str
    cell_type: Literal['prompt', 'reasoning', 'metric', 'visualization', 'table', 'insight', 'suggestion']
    title: str
    content: Any # JSON object
    dependencies: Dict[str, Any] = Field(default_factory=dict) # {"depends_on": "cell_id"}
    ui_hints: Dict[str, Any] = Field(default_factory=dict) # {"collapsible": bool, "emphasis": str}

class AnalysisMetadata(BaseModel):
    domain: Literal["health", "medical", "life_sciences", "general"]
    analysis_type: Literal["descriptive", "diagnostic", "exploratory", "comparative"]
    generated_at: str
    confidence_level: Literal["high", "medium", "exploratory"]

class NotebookOutput(BaseModel):
    notebook_id: str
    analysis_metadata: AnalysisMetadata
    cells: List[NotebookCell]

