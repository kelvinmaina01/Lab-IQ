def planner_node(state: AgentState):
    """
    Role: ARCHITECT (Gemini)
    Goal: Understands the user request and dataset context. Creates a high-level plan.
    """
    logger.info("--- NODE: PLANNER (GEMINI) ---")
    
    # Use Groq FIRST for speed (Llama-3-70b is very capable planner)
    model = groq_llm or gemini_llm or hf_llm
    if model:
        logger.info(f"PLANNER SELECTED MODEL: {type(model).__name__}")
    else:
        raise ValueError("No AI Model configured!")

    prompt = ChatPromptTemplate.from_template("""
    You are Antigravity, an expert Health Data Analyst.
    
    USER REQUEST: "{user_prompt}"
    
    DATASET CONTEXT:
    {dataset_context}
    
    Your goal is to PLAN a rigorous analysis.
    Do NOT write code yet. Just the "Thought Process".
    
    Output a JSON structure matching 'AnalystPlan' with:
    - objective_understanding
    - steps (rationale)
    - data_requirements
    - potential_challenges
    """)
    
    chain = prompt | model.with_structured_output(AnalystPlan)
    
    try:
        plan = chain.invoke({
            "user_prompt": state["user_prompt"],
            "dataset_context": json.dumps(state["dataset_context"], default=str)[:3000] # Truncate for safety
        })
        return {"plan": plan}
    except Exception as e:
        logger.error(f"Planning failed: {e}")
        # Fallback plan if structured output fails
        return {"plan": AnalystPlan(
            objective_understanding="Analyze data based on request",
            steps=[PlanStep(step_number=1, activity="Analyze Data", rationale="Standard analysis")],
            data_requirements=[],
            potential_challenges=["AI Error"]
        )}

def coder_node(state: AgentState):
    """
    Role: ENGINEER (Groq)
    Goal: Takes the plan and writes efficient Pandas/Matplotlib code.
    """
    logger.info("--- NODE: CODER (GROQ) ---")
    
    # Prefer Groq for coding (Llama-3 is great at Python)
    model = groq_llm or gemini_llm or hf_llm
    
    plan_str = state["plan"].model_dump_json() if state["plan"] else "No plan"
    
    prompt = ChatPromptTemplate.from_template("""
    You are an expert Python Data Engineer.
    
    PLAN:
    {plan}
    
    DATASET PROPERTIES:
    {dataset_context}
    
    TASK: Write Python code to execute this plan.
    RULES:
    1. Assume 'df' is already loaded with the data.
    2. You MUST create a dictionary called 'metrics' for key numbers.
    3. You MUST use plt.show() or simply create plots (the sandbox captures them).
    4. Handle missing data gracefully.
    5. No markdown fencing around the code logic if possible, or simple block.
    
    Output JSON 'CodingTask' with 'python_code' and 'explanation'.
    """)
    
    chain = prompt | model.with_structured_output(CodingTask)
    
    try:
        task = chain.invoke({
            "plan": plan_str,
            "dataset_context": json.dumps(state["dataset_context"], default=str)[:2000]
        })
        return {"code_task": task}
    except Exception as e:
        # Fallback basic code
        logger.error(f"Coding failed: {e}")
        return {"code_task": CodingTask(python_code="print('Error generating code')", explanation="Failed")}

def executor_node(state: AgentState):
    """
    Role: EXECUTOR (Sandbox)
    Goal: Run the code safely.
    """
    logger.info("--- NODE: EXECUTOR (SANDBOX) ---")
    
    code = state["code_task"].python_code if state["code_task"] else ""
    
    # Extract data rows from context hack (passed from app.py)
    data_rows = state["dataset_context"].get("data_rows", [])
    if not data_rows:
        return {
            "execution_success": False, 
            "execution_error": "No data rows provided for execution",
            "execution_logs": "Error: missing data",
            "execution_artifacts": {}
        }
        
    import pandas as pd
    df = pd.DataFrame(data_rows)
    
    sandbox = LocalSandbox()
    result = sandbox.execute(code, df)
    
    return {
        "execution_success": result.success,
        "execution_logs": result.output_log,
        "execution_error": result.error,
        "execution_artifacts": result.artifacts
    }

def synthesis_node(state: AgentState):
    """
    Role: SYNTHESIZER (Gemini/Groq)
    Role: Taking results and formatting into the Antigravity Notebook XML Schema.
    """
    logger.info("--- NODE: SYNTHESIZER ---")
    
    model = gemini_llm or groq_llm
    
    prompt = ChatPromptTemplate.from_template("""
    You are the Antigravity Synthesis Engine.
    
    USER REQUEST: {user_prompt}
    
    PLAN: {plan_summary}
    
    EXECUTION LOGS: {logs}
    METRICS: {metrics}
    
    Construct a Final Analysis Notebook observing the strict SystemContract.
    Return a JSON object matching 'NotebookOutput'.
    
    - Domain: health/medical
    - Confidence: Check metrics
    - Cells: Prompt, Reasoning, Metrics, Visualization (if charts exist), Insight, Suggestion.
    """)
    
    chain = prompt | model.with_structured_output(NotebookOutput)
    
    try:
        final_output = chain.invoke({
            "user_prompt": state["user_prompt"],
            "plan_summary": str(state["plan"].steps) if state["plan"] else "N/A",
            "logs": state["execution_logs"],
            "metrics": str(state["execution_artifacts"].get("metrics", {}))
        })
        
        # Inject chart artifacts manually since LLM can't see the images
        if state["execution_artifacts"].get("chart"):
            # Find viz cell or append one
            chart_b64 = state["execution_artifacts"]["chart"]
            # Look for a placeholder viz cell or create one
            viz_cell = NotebookCell(
                cell_id=f"viz_{uuid.uuid4().hex[:8]}",
                cell_type="visualization",
                title="Generated Visualization",
                content={"chart_type": "image", "data": chart_b64},
                ui_hints={"collapsible": False, "emphasis": "normal"}
            )
            # Insert before insight/suggestion
            final_output.cells.insert(-2, viz_cell) 

        return {"final_notebook": final_output}
        
    except Exception as e:
        logger.error(f"Synthesis failed: {e}")
        return {"execution_error": str(e)}

