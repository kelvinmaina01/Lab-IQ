async def stream_notebook_generation(user_prompt: str, dataset_context: Dict[str, Any], data_rows: List[Dict]):
    """
    Generator that yields JSON events for the WebSocket.
    Uses 'astream_events' to provide real-time token-level feedback.
    """
    # Prepare initial state
    dataset_context["data_rows"] = data_rows # Inject for executor
    
    inputs = {
        "user_prompt": user_prompt,
        "dataset_context": dataset_context
    }
    
    # Track current active node to know what the token belongs to
    current_node = None
    
    # Use astream_events to catch internal LLM streaming tokens
    async for event in app_graph.astream_events(inputs, version="v1"):
        kind = event["event"]
        
        # 1. NODE ENTRIES - Set Context
        if kind == "on_chain_start":
            node_name = event["name"]
            if node_name == "planner":
                current_node = "planner"
                yield {"type": "status", "phase": "planning", "message": "Architecting analysis plan..."}
            elif node_name == "coder":
                current_node = "coder"
                yield {"type": "status", "phase": "coding", "message": "Engineering Python solution..."}
            elif node_name == "executor":
                current_node = "executor"
                yield {"type": "status", "phase": "execution", "message": "Executing in Sandbox..."}
            elif node_name == "synthesizer":
                current_node = "synthesizer"
                yield {"type": "status", "phase": "synthesis", "message": "Synthesizing final report..."}

        # 2. LLM TOKENS - Stream Content
        elif kind == "on_chat_model_stream":
            content = event["data"]["chunk"].content
            if content:
                # Differentiate based on the active node
                if current_node == "planner":
                    # Stream thought process tokens
                    yield {"type": "token", "target": "thought", "chunk": content}
                elif current_node == "coder":
                    # Stream code tokens
                    yield {"type": "token", "target": "code", "chunk": content}

        # 3. NODE OUTPUTS - Final structural updates (keep these for safety/validation)
        elif kind == "on_chain_end":
            data = event["data"].get("output")
            if not data: continue
            
            node_name = event["name"]
            
            if node_name == "executor":
                 # Execution logs aren't streamed by LLM, so we yield them here
                 yield {
                    "type": "execution",
                    "logs": data.get("execution_logs", ""),
                    "success": data.get("execution_success", False)
                }
            elif node_name == "synthesizer" and "final_notebook" in data:
                 yield {
                    "type": "complete",
                    "payload": data["final_notebook"].model_dump()
                }
            elif node_name == "synthesizer" and "execution_error" in data:
                 yield {
                    "type": "error",
                    "error": data["execution_error"]
                }

