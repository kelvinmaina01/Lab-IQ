class AgentState(TypedDict):
    """
    Streaming State. 
    We use strictly typed updates to track the flow.
    """
    user_prompt: str
    dataset_context: Dict[str, Any] # Metadata + Data Preview
    
    # Step 1: Planning (Gemini)
    plan: Optional[AnalystPlan]
    
    # Step 2: Coding (Groq)
    code_task: Optional[CodingTask]
    
    # Step 3: Execution (Sandbox)
    execution_logs: Optional[str]
    execution_artifacts: Dict[str, Any] # metrics, charts
    execution_success: bool
    execution_error: Optional[str]
    
    # Step 4: Synthesis (Gemini/Groq)
    final_notebook: Optional[NotebookOutput]

