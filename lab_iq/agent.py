workflow = StateGraph(AgentState)

workflow.add_node("planner", planner_node)
workflow.add_node("coder", coder_node)
workflow.add_node("executor", executor_node)
workflow.add_node("synthesizer", synthesis_node)

workflow.set_entry_point("planner")

workflow.add_edge("planner", "coder")
workflow.add_edge("coder", "executor")

def check_execution(state):
    """Conditional edge: Did execution succeed?"""
    if state["execution_success"]:
        return "synthesizer"
    else:
        # In a real system, we'd loop back to 'coder' to fix bugs (Self-Healing)
        # For V1, we proceed to synthesis to report the error
        return "synthesizer"

workflow.add_conditional_edges("executor", check_execution)
workflow.add_edge("synthesizer", END)

app_graph = workflow.compile()

